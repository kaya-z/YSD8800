; ============================================================
; YSD8800 FORTH KERNEL (ISA2.1 / hasm完全準拠)
; ============================================================

.vector reset start

; ------------------------------------------------------------
; メモリ変数
; ------------------------------------------------------------

        .ORG 0x0200

RP:
	DW 0xF000      ; リターンスタックポインタ

; ------------------------------------------------------------
; コード
; ------------------------------------------------------------

        .ORG 0x0100

start:
        LDW SP, #0xF800      ; データスタック
        LDW X,  cold_start  ; IP
        JMP next

; ------------------------------------------------------------
; NEXT（インタプリタ）
; ------------------------------------------------------------

next:
        LDW A, [X]
        ADDI X, #2
        JMP [A]

; ------------------------------------------------------------
; リターンスタック
; ------------------------------------------------------------

rpush:
        LDW B, [RP]
        SUBI B, #2
        STW X, [B]
        STW B, [RP]
        RET

rpop:
        LDW B, [RP]
        LDW X, [B]
        ADDI B, #2
        STW B, [RP]
        RET

; ------------------------------------------------------------
; 制御
; ------------------------------------------------------------
; ( addr -- )
enter:                  
        JSR rpush
        POP X
        JMP next

exit:
        JSR rpop
        JMP next

; ------------------------------------------------------------
; スタック操作
; ------------------------------------------------------------
; ( n -- )
drop:                   
        POP A
        JMP next
; ( n -- n n )
dup:                    
        POP A
        PUSH A
        PUSH A
        JMP next
; ( n1 n2 -- n2 n1 )
swap:                   
        POP A
        POP B
        PUSH A
        PUSH B
        JMP next

; ------------------------------------------------------------
; 算術
; ------------------------------------------------------------
; ( n1 n2 -- n )
add:                    
        POP A
        POP B
        ADD A, B
        PUSH A
        JMP next

; ------------------------------------------------------------
; リテラル
; ------------------------------------------------------------

lit:
        LDW A, [X]
        ADDI X, 2
        PUSH A
        JMP next

; ------------------------------------------------------------
; テストコード
; ------------------------------------------------------------

cold_start:
        DW lit
        DW 10

        DW lit
        DW 20

        DW add
        DW dup
        DW drop

        DW halt_word

; ------------------------------------------------------------
; HALT
; ------------------------------------------------------------

halt_word:
        HALT
