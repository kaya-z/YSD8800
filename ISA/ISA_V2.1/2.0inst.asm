; ==========================================
; YSD8800 ISA2.0 全命令テスト (vector memory model)
; ==========================================
; 前提:
;   vector table at 0x0000
;   reset = 0
;   irq0  = 1
;   syscall = 4
;
; 結果:
;   0x2000〜 に結果を書き込む
;   成功 = 1 または期待値
; ==========================================

.vector reset   0x0100
.vector irq0    irq0_handler
.vector syscall syscall_handler

; ==========================================
; main
; ==========================================

.org 0x0100
start:

    DI
    LDW SP, #0x7ff0
    EI

; ------------------------------------------
; MOV
; ------------------------------------------
test_mov:
    LDW A, #0x1234
    MOV B, A
    STW B, [0x2000]

; ------------------------------------------
; LDW imm
; ------------------------------------------
test_ldw_imm:
    LDW A, #0xabcd
    STW A, [0x2002]

; ------------------------------------------
; absolute memory
; ------------------------------------------
test_abs:
    LDW A, #0x5555
    STW A, [0x3000]
    LDW B, [0x3000]
    STW B, [0x2004]

; ------------------------------------------
; register indirect
; ------------------------------------------
test_reg_ind:
    LDW A, #0x3002
    LDW B, #0x7777
    STW B, [A]
    LDW X, [A]
    STW X, [0x2006]

; ------------------------------------------
; X indexed
; ------------------------------------------
test_x_index:
    LDW X, #0x4000
    LDW A, #0x8888
    STW A, [X + #2]
    LDW B, [X + #2]
    STW B, [0x2008]

; ------------------------------------------
; ADD / ADDI
; ------------------------------------------
test_add:
    LDW A, #5
    LDW B, #3
    ADD A, B
    STW A, [0x200a]

test_addi:
    LDW A, #10
    ADDI A, #7
    STW A, [0x200c]

; ------------------------------------------
; SUB / SUBI
; ------------------------------------------
test_sub:
    LDW A, #10
    LDW B, #4
    SUB A, B
    STW A, [0x200e]

test_subi:
    LDW A, #20
    SUBI A, #5
    STW A, [0x2010]

; ------------------------------------------
; CMP / BEQ
; ------------------------------------------
test_cmp:
    LDW A, #5
    LDW B, #5
    CMP A, B
    BEQ cmp_ok

    LDW A, #0xdead
    STW A, [0x2012]
    JMP test_cmpi

cmp_ok:
    LDW A, #1
    STW A, [0x2012]

; ------------------------------------------
; CMPI / BNE
; ------------------------------------------
test_cmpi:
    LDW A, #3
    CMPI A, #4
    BNE cmpi_ok

    LDW A, #0xdead
    STW A, [0x2014]
    JMP test_blt

cmpi_ok:
    LDW A, #1
    STW A, [0x2014]

; ------------------------------------------
; BLT
; ------------------------------------------
test_blt:
    LDW A, #1
    LDW B, #2
    CMP A, B
    BLT blt_ok

    LDW A, #0xdead
    STW A, [0x2016]
    JMP test_bge

blt_ok:
    LDW A, #1
    STW A, [0x2016]

; ------------------------------------------
; BGE
; ------------------------------------------
test_bge:
    LDW A, #5
    LDW B, #3
    CMP A, B
    BGE bge_ok

    LDW A, #0xdead
    STW A, [0x2018]
    JMP test_jmp

bge_ok:
    LDW A, #1
    STW A, [0x2018]

; ------------------------------------------
; JMP (rel)
; ------------------------------------------
test_jmp:
    JMP jmp_target

    LDW A, #0xdead
    STW A, [0x201a]

jmp_target:
    LDW A, #1
    STW A, [0x201a]

; ------------------------------------------
; JSR / RET
; ------------------------------------------
test_jsr:
    JSR func
    STW A, [0x201c]
    JMP test_syscall

func:
    LDW A, #42
    RET

; ------------------------------------------
; SYSCALL → handler increments B
; ------------------------------------------
test_syscall:
    LDW B, #0
    SYSCALL #1

wait_sc:
    CMPI B, #1
    BNE wait_sc

    STW B, [0x201e]

; ------------------------------------------
; IRQ0 (timer等で発生想定)
; ------------------------------------------
test_irq:

    LDW B, #0
    EI

wait_irq:
    CMPI B, #5
    BLT wait_irq

    STW B, [0x2020]

; ------------------------------------------
; BRK
; ------------------------------------------
    BRK

; ------------------------------------------
; HALT
; ------------------------------------------
    HALT

; ==========================================
; IRQ0 handler
; B++
; ==========================================
irq0_handler:
    ADDI B, #1
    IRET

; ==========================================
; SYSCALL handler
; B++
; ==========================================
syscall_handler:
    ADDI B, #1
    IRET
