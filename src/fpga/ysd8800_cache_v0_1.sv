//  ------------------------------------------------------------
//  ★段2 のスコープ（意図的な未実装を明記する）★
//  ------------------------------------------------------------
//    実装する:
//      (1) CPU 側 ⇔ ブリッジ側の ★純組合せバイパス★ (CEN=0 経路)
//      (2) burst_len の駆動 (CEN=0 時は常に 1)
//      (3) beat_valid / psram_rdata の受け口（psram_clk 直結・M-10 ②③）
//          → ★段2 では受けるだけで使わない★
//    ★実装しない（段3 以降）★:
//      - tag_ram / valid_r / データ RAM (DPB)
//      - ヒット判定・ラインフィル・fill_hit_byte_r (M-9)
//      - data_q_valid (M-11)
//      - ライトスルー（段4）・FLUSH / CEN 立上り無効化（段5）
//
//  ------------------------------------------------------------
//  ★G-0 成立の構造的根拠（最重要・KY-B8）★
//  ------------------------------------------------------------
//    設計書 §7.1:「CEN=0 のとき、信号は純組合せでバイパスされ、
//                  レジスタを一切経由しない。」
//
//    本モジュールは段2 において ★always_ff を1つも持たない★。
//    したがって CEN の値によらず、CPU⇔ブリッジ間の
//    パスに遅延段は存在せず、サイクル数は挿入前と完全に一致する。
//
//    ★レジスタを1段でも入れた瞬間に G-0 は落ちる。★
//    段3 でヒット経路を追加する際も、CEN=0 の経路だけは
//    純組合せのまま保つこと。
//
//  ------------------------------------------------------------
//  ★命名について★
//    段2 時点で CEN 入力を受けるが、内部では ★使用しない★。
//    未使用のまま結線するのは、段3 で経路を切り替える際に
//    membus 側の配線変更を再度発生させないためである
//    (1変更1検証: 配線変更と機能追加を同じ段に混ぜない)。
// ============================================================


module ysd8800_cache_v0_1 #(
    parameter int PHYS_AW   = 20,          // 物理アドレス幅
    parameter int BLEN_W    = 6,           // burst_len 幅 ($clog2(32)+1)
    parameter int LINE_SIZE = 32           // ラインサイズ(バイト) ※段3で使用
)(
    input  logic                 cpu_clk,
    input  logic                 cpu_rst_n,

    // ---- CCR（mmio_stub より）----
    //   段2 では ★意図的に未使用★（バイパス固定）。段3 で経路選択に使う。
    input  logic                 ccr_cen_i,
    input  logic                 ccr_flush_pulse_i,

    // ---- CPU 側（MMU 出力・上流）----
    input  logic [PHYS_AW-1:0]   cpu_phys_addr_i,
    input  logic [7:0]           cpu_wdata_i,
    output logic [7:0]           cpu_rdata_o,
    input  logic                 cpu_rd_i,
    input  logic                 cpu_wr_i,
    output logic                 cpu_ready_o,

    // ---- ブリッジ側（下流・cpu_clk ドメイン）----
    output logic [PHYS_AW-1:0]   br_phys_addr_o,
    output logic [7:0]           br_wdata_o,
    input  logic [7:0]           br_rdata_i,
    output logic                 br_rd_o,
    output logic                 br_wr_o,
    input  logic                 br_ready_i,

    // ---- psram_ctrl 直結（M-10 ①②③）----
    output logic [BLEN_W-1:0]    burst_len_o,      // ① cpu_clk 側
    input  logic                 psram_clk,        // ② ③ のドメイン
    input  logic                 psram_rst_n,
    input  logic                 beat_valid_i,     // ② ★cdc_bridge を経由しない★
    input  logic [7:0]           psram_rdata_i     // ③ 同上
);

    // ------------------------------------------------------------
    // 段2: 純組合せバイパス（設計書 §7.1）
    //   ★always_ff を持たないこと自体が G-0 の保証である★
    // ------------------------------------------------------------
    //   下り（CPU → ブリッジ）
    assign br_phys_addr_o = cpu_phys_addr_i;
    assign br_wdata_o     = cpu_wdata_i;
    assign br_rd_o        = cpu_rd_i;
    assign br_wr_o        = cpu_wr_i;

    //   上り（ブリッジ → CPU）
    assign cpu_rdata_o    = br_rdata_i;
    assign cpu_ready_o    = br_ready_i;

    // ------------------------------------------------------------
    // burst_len の駆動（M-10 ①）
    // ------------------------------------------------------------
    //   ★CEN=0 時は常に 1★（設計書 §1.2）。
    //   段2 は CEN によらず 1 固定であり、②-A の
    //   .burst_len(PS_BLEN_W'(1)) と ★ビット単位で同一★である。
    //   → 配線変更の非退行が G-0 で検証できる（設計書 §1.2）。
    assign burst_len_o = BLEN_W'(1);

    // ------------------------------------------------------------
    // ★段2 で意図的に未使用の入力★
    // ------------------------------------------------------------
    //   ccr_cen_i / ccr_flush_pulse_i … 段3・段5 で使用
    //   beat_valid_i / psram_rdata_i  … 段3 のラインフィル DPB 書込で使用
    //   psram_clk / psram_rst_n       … 段3 の DPB 書込側ドメイン
    //
    //   ★未使用入力を今のうちにポートとして確定させておく理由★
    //     段3 で membus の配線を再度変更せずに済ませるため。
    //     配線変更(段2)と機能追加(段3)を分離し、G-0 が落ちたときの
    //     被疑対象を一方に限定する（1変更1検証）。
    //
    //   Icarus は未使用入力を警告しないが、意図を明示するため
    //   ダミー参照は ★置かない★（置くと合成時に論理が残る恐れがある）。

endmodule


