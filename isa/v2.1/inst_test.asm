; ============================================================
; YSD8800 ISA2.1 FULL COVERAGE TEST
; (EXT + ISA2.0)
; ============================================================

.ORG 0000

; --- Vector Table ---
        DW start        ; reset
        DW 0            ; irq0
        DW 0            ; irq1
        DW align_err    ; align
        DW 0            ; syscall

; ============================================================
; CODE
; ============================================================

.ORG 0100

start:

; ------------------------------------------------------------
; 初期化
; ------------------------------------------------------------
        LDW SP, #0xF000

; ------------------------------------------------------------
; MOV / LDW / STW
; ------------------------------------------------------------
        LDW A, #0x1234
        MOV B, A
        STW B, [0x0800]
        LDW A, [0x0800]

; ------------------------------------------------------------
; レジスタ間接
; ------------------------------------------------------------
        LDW X, #0x0800
        LDW B, [X]
        STW B, [X]

; ------------------------------------------------------------
; X+imm
; ------------------------------------------------------------
        LDW A, #0x5678
        STW A, [X + 2]
        LDW B, [X + 2]

; ------------------------------------------------------------
; 算術
; ------------------------------------------------------------
        LDW A, #10
        LDW B, #3

        ADD A, B
        SUB A, B

        ADDI A, #5
        SUBI A, #2

        CMP A, B
        CMPI A, #10

; ------------------------------------------------------------
; Branch（全パターン）
; ------------------------------------------------------------
        LDW A, #0
        CMP A, A
        BEQ beq_ok

fail:
	BRK

beq_ok:
        LDW A, #1
        CMP A, #0
        BNE bne_ok
        JMP fail

bne_ok:
        LDW A, #-1
        CMP A, #0
        BLT blt_ok
        JMP fail

blt_ok:
        LDW A, #1
        CMP A, #0
        BGE bge_ok
        JMP fail

bge_ok:

; ------------------------------------------------------------
; JSR / RET
; ------------------------------------------------------------
        JSR sub_test
        JMP after_sub

sub_test:
        LDW A, #0xAAAA
        RET

after_sub:

; ============================================================
; EXT TEST
; ============================================================

; ------------------------------------------------------------
; PUSH / POP
; ------------------------------------------------------------
        LDW A, #0x1111
        LDW B, #0x2222

        PUSH A
        PUSH B

        LDW A, #0
        LDW B, #0

        POP B
        POP A

        CMP A, #0x1111
        BNE fail

        CMP B, #0x2222
        BNE fail

; ------------------------------------------------------------
; LDB / STB (addr)
; ------------------------------------------------------------
        LDW A, #0x00AA
        STB A, [0x0810]

        LDW A, #0
        LDB A, [0x0810]

        CMP A, #0x00AA
        BNE fail

; ------------------------------------------------------------
; LDB / STB (Bレジスタ)
; ------------------------------------------------------------
        LDW B, #0x00CC
        STB B, [0x0812]

        LDW B, #0
        LDB B, [0x0812]

        CMP B, #0x00CC
        BNE fail

; ------------------------------------------------------------
; LDB / STB ([X])
; ------------------------------------------------------------
        LDW X, #0x0820

        LDW A, #0x00DD
        STB A, [X]

        LDW A, #0
        LDB A, [X]

        CMP A, #0x00DD
        BNE fail

; ------------------------------------------------------------
; Bレジスタ + [X]
; ------------------------------------------------------------
        LDW B, #0x00EE
        STB B, [X]

        LDW B, #0
        LDB B, [X]

        CMP B, #0x00EE
        BNE fail

; ============================================================
; 正常終了
; ============================================================

success:
        HALT

; ============================================================
; 例外
; ============================================================

align_err:
        BRK
